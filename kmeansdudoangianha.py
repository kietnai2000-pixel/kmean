import streamlit as st
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, mean_absolute_error, mean_squared_error

# 1. Đọc dữ liệu
train_path = '/content/nhom4_train_data.xlsx'
test_path = '/content/nhom4_test_data.xlsx'

df_train = pd.read_excel(train_path)
df_test = pd.read_excel(test_path)

print("Dữ liệu huấn luyện (Train):")
display(df_train.head())
print("Dữ liệu kiểm thử (Test):")
display(df_test.head())

# 2. Tiền xử lý dữ liệu & Chuẩn hóa
# Giả định cột chứa giá nhà là 'price' hoặc 'Giá' (tùy thuộc vào dataset của bạn, ta tìm cột phù hợp)
possible_price_cols = [col for col in df_train.columns if 'price' in col.lower() or 'giá' in col.lower() or 'gia' in col.lower()]
if len(possible_price_cols) > 0:
    price_col = possible_price_cols[0]
else:
    price_col = df_train.select_dtypes(include=[np.number]).columns[-1] # Mặc định lấy cột số cuối cùng nếu không tìm thấy tên

print(f"Cột giá nhà được xác định là: {price_col}")

# Lấy danh sách các cột đặc trưng dạng số để phân cụm (loại bỏ cột giá nhà nếu muốn phân cụm dựa trên các thông số kỹ thuật khác, hoặc giữ lại để phân cụm theo giá)
features = df_train.select_dtypes(include=[np.number]).columns.tolist()

# Chuẩn hóa dữ liệu
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(df_train[features])
X_test_scaled = scaler.transform(df_test[features])

# 3. Tìm số cụm tối ưu K qua WCSS (Elbow Method)
wcss = []
K_range = range(1, 11)
for k in K_range:
    kmeans = KMeans(n_clusters=k, init='k-means++', random_state=42, n_init=10)
    kmeans.fit(X_train_scaled)
    wcss.append(kmeans.inertia_)

# Vẽ biểu đồ Elbow
plt.figure(figsize=(10, 5))
plt.plot(K_range, wcss, marker='o', linestyle='--', color='b')
plt.title('Phương pháp khuỷu tay (Elbow Method)')
plt.xlabel('Số lượng cụm K')
plt.ylabel('WCSS')
plt.grid(True)
plt.show()

# 4. Khởi tạo K-Means với K = 3 cụm theo yêu cầu
kmeans = KMeans(n_clusters=3, init='k-means++', random_state=42, n_init=10)
kmeans.fit(X_train_scaled)

# Gán cụm và tính khoảng cách đến centroid cho tập Train
train_clusters = kmeans.predict(X_train_scaled)
train_distances = kmeans.transform(X_train_scaled)

df_train['Cluster'] = train_clusters
for i in range(3):
    df_train[f'Dist_to_Centroid_{i}'] = train_distances[:, i]

print("Dữ liệu huấn luyện sau khi gán cụm và tính khoảng cách đến Centroid:")
display(df_train.head())

# 5. Hiển thị Tâm Centroid và phân tích đặc trưng trung bình của từng cụm
centroids_scaled = kmeans.cluster_centers_
centroids_original = scaler.inverse_transform(centroids_scaled)

df_centroids = pd.DataFrame(centroids_original, columns=features)
df_centroids['Cluster'] = [0, 1, 2]
print("Giá trị trung bình gốc (Tâm cụm Centroid) của từng cụm:")
display(df_centroids)

"""```markdown
### Giải thích ý nghĩa từng cụm (Dựa vào giá trị trung bình ở bảng trên):
- **Cụm 0 (Phân khúc Thấp / Bình dân)**: Thường có giá trị trung bình thấp nhất, diện tích nhỏ hơn hoặc ít tiện ích hơn.
- **Cụm 1 (Phân khúc Trung cấp)**: Có mức giá và đặc trưng trung bình, phù hợp với đa số hộ gia đình.
- **Cụm 2 (Phân khúc Cao cấp / Biệt thự)**: Có giá nhà trung bình cao nhất, diện tích lớn, nhiều phòng và dịch vụ đi kèm vượt trội.
```
"""

# 6. Đánh giá mô hình trên tập Test
test_clusters = kmeans.predict(X_test_scaled)
test_distances = kmeans.transform(X_test_scaled)

df_test['Cluster'] = test_clusters
for i in range(3):
    df_test[f'Dist_to_Centroid_{i}'] = test_distances[:, i]

# Định nghĩa giá trị dự báo cho mỗi cụm bằng trung bình giá thực tế của cụm đó trong tập train
cluster_price_map = df_train.groupby('Cluster')[price_col].mean().to_dict()
df_test['Predicted_Price'] = df_test['Cluster'].map(cluster_price_map)

# Đánh giá sai số ước tính (Regression Metrics)
mae = mean_absolute_error(df_test[price_col], df_test['Predicted_Price'])
rmse = np.sqrt(mean_squared_error(df_test[price_col], df_test['Predicted_Price']))

print(f"Sai số tuyệt đối trung bình (MAE): {mae:,.2f}")
print(f"Sai số bình phương trung bình dạng căn (RMSE): {rmse:,.2f}")

# Để đánh giá bằng Accuracy, Precision, Recall, F1-Score:
# Ta sử dụng pd.qcut để chia giá nhà thực tế trên tập Test thành đúng 3 nhóm (0, 1, 2) theo tỷ lệ bằng nhau
actual_categories = pd.qcut(df_test[price_col], q=3, labels=[0, 1, 2])

accuracy = accuracy_score(actual_categories, df_test['Cluster'])
precision = precision_score(actual_categories, df_test['Cluster'], average='weighted', zero_division=0)
recall = recall_score(actual_categories, df_test['Cluster'], average='weighted', zero_division=0)
f1 = f1_score(actual_categories, df_test['Cluster'], average='weighted', zero_division=0)

print(f"Accuracy: {accuracy:.4f}")
print(f"Precision (Weighted): {precision:.4f}")
print(f"Recall (Weighted): {recall:.4f}")
print(f"F1-Score (Weighted): {f1:.4f}")

# 7. Trực quan hóa kết quả bằng biểu đồ
plt.figure(figsize=(18, 5))

# Biểu đồ 1: Phân bố giá nhà thực tế
plt.subplot(1, 3, 1)
sns.histplot(df_test[price_col], kde=True, color='purple')
plt.title('Biểu đồ phân bố giá nhà (Test Set)')
plt.xlabel('Giá nhà')

# Biểu đồ 2: Trực quan hóa các cụm nhà và tâm Centroid (giả sử vẽ theo giá và cột đặc trưng chính thứ 2)
plt.subplot(1, 3, 2)
sns.scatterplot(data=df_test, x=features[0], y=price_col, hue='Cluster', palette='Set1', style='Cluster', s=100)
plt.title('Biểu đồ phân cụm nhà')
plt.xlabel(features[0])
plt.ylabel('Giá nhà')

# Biểu đồ 3: So sánh Giá thực tế và Giá dự tính
plt.subplot(1, 3, 3)
plt.scatter(df_test[price_col], df_test['Predicted_Price'], alpha=0.6, color='g')
plt.plot([df_test[price_col].min(), df_test[price_col].max()], [df_test[price_col].min(), df_test[price_col].max()], 'r--', lw=2)
plt.title('Thực tế vs Dự tính')
plt.xlabel('Giá thực tế')
plt.ylabel('Giá dự tính')

plt.tight_layout()
plt.show()
